                    href="https://github.com/JulieStenning/Rust-Embroidery-Catalogue"
                    target="_blank"
                    rel="noopener noreferrer"
                    class="text-[var(--text-brand)] hover:underline font-medium break-all"
                    >https://github.com/JulieStenning/Rust-Embroidery-Catalogue</a
                  >.
                </p>
              </div>
            </div>
            <pre
              class="whitespace-pre-wrap text-xs text-[var(--text-secondary)] bg-[var(--surface-card-subtle)] border border-[var(--border-default)] rounded-lg p-4 overflow-x-auto font-mono shadow-inner licence-primary-text">{primaryLicense}</pre>
            {#if hasThirdPartyNotices}
              <h3
                data-testid="licence-third-party-notices-heading"
                class="ui-section-label font-semibold text-[var(--text-primary)] mt-6 mb-2"
              >
                Third-Party Notices
              </h3>
              <pre
                data-testid="licence-third-party-notices"
                class="whitespace-pre-wrap text-xs text-[var(--text-secondary)] bg-[var(--surface-card-subtle)] border border-[var(--border-default)] rounded-lg p-4 overflow-x-auto font-mono shadow-inner licence-notice-text">{noticeText}</pre>
            {/if}
          </div>
        {:else if activeLicenceTab === "rust"}
          <div data-testid="licence-rust-tab">
            <div class="flex items-center justify-between gap-4 mb-4">
              <div>
                <h2 class="text-lg font-bold text-[var(--text-primary)] font-sans">
                  Rust Dependencies
                </h2>
                <p class="text-sm text-[var(--text-secondary)] mt-1">
                  Open-source Rust crates used by the Embroidery Catalogue backend.
                </p>
              </div>
            </div>
            <DependencyLicenceTable
              items={rustLicenceRows}
              dependencyType="Rust"
              emptyMessage="No Rust licence data is available."
            />
          </div>
        {:else}
          <div data-testid="licence-frontend-tab">
            <div class="flex items-center justify-between gap-4 mb-4">
              <div>
                <h2 class="text-lg font-bold text-[var(--text-primary)] font-sans">
                  Frontend Dependencies
                </h2>
                <p class="text-sm text-[var(--text-secondary)] mt-1">
                  Open-source NPM packages used by the Embroidery Catalogue frontend.
                </p>
              </div>
            </div>
            <DependencyLicenceTable
              items={frontendLicenceRows}
              dependencyType="Frontend"
              emptyMessage="No frontend packages recorded."
            />
          </div>
        {/if}
      </div>
    </div>
  </div>
{:else}
  <div class="max-w-5xl mx-auto space-y-4 font-sans">
    <div class="route-card rounded-xl shadow p-6">
      {#if loading}
        <p class="text-sm text-[var(--text-muted)]">Loading document...</p>
      {:else if error}
        <p class="notice-error rounded p-3 text-sm">{error}</p>
      {:else if documentItem?.document_text}
        {#if shouldRenderAsHtml(documentItem)}
          <div
            class="text-sm text-[var(--text-secondary)] bg-[var(--surface-card-subtle)] border border-[var(--border-default)] rounded-lg p-4 space-y-4 shadow-inner"
          >
            {@html documentItem.document_text}
          </div>
        {:else if shouldRenderAsMarkdown(documentItem)}
          <div
            class="text-sm text-[var(--text-secondary)] bg-[var(--surface-card-subtle)] border border-[var(--border-default)] rounded-lg p-4 prose dark:prose-invert max-w-none shadow-inner document-markdown"
          >
            {@html renderMarkdown(documentItem.document_text)}
          </div>
        {:else}
          <pre
            class="whitespace-pre-wrap text-sm text-[var(--text-secondary)] bg-[var(--surface-card-subtle)] border border-[var(--border-default)] rounded-lg p-4 overflow-x-auto font-mono shadow-inner">{documentItem.document_text}</pre>
        {/if}
      {:else}
        <p class="text-sm text-[var(--text-muted)] italic">Document content is unavailable.</p>
      {/if}
    </div>
  </div>
{/if}

